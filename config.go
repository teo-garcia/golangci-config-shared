// Package golangciconfig exposes the canonical golangci-lint configuration
// shared by the teo-garcia Go templates.
//
// golangci-lint has no native config inheritance, so this package provides it:
// [Merge] deep-merges a repo-local overlay onto the shared baseline, and
// [Write] materializes the result to disk for `golangci-lint run --config`.
package golangciconfig

import (
	"bytes"
	_ "embed"
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

//go:embed golangci.yml
var baseline []byte

// Baseline returns the canonical configuration as raw YAML.
//
// The returned slice is a copy; mutating it does not affect later calls.
func Baseline() []byte {
	out := make([]byte, len(baseline))
	copy(out, baseline)
	return out
}

// Merge deep-merges overlay onto the shared baseline and returns the result as
// YAML.
//
// Maps are merged key by key at every depth. Every other kind of value —
// scalars and sequences alike — is replaced wholesale by the overlay. Lists are
// deliberately not concatenated: a template that narrows `linters.enable` must
// be able to shrink it, and an appending merge would make that impossible.
//
// A nil or empty overlay yields the baseline unchanged.
func Merge(overlay []byte) ([]byte, error) {
	base := map[string]any{}
	if err := yaml.Unmarshal(baseline, &base); err != nil {
		return nil, fmt.Errorf("parse baseline config: %w", err)
	}

	if len(bytes.TrimSpace(overlay)) > 0 {
		over := map[string]any{}
		if err := yaml.Unmarshal(overlay, &over); err != nil {
			return nil, fmt.Errorf("parse overlay config: %w", err)
		}
		base = mergeMaps(base, over)
	}

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(base); err != nil {
		return nil, fmt.Errorf("encode merged config: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("encode merged config: %w", err)
	}

	header := "# Generated by golangci-config-shared. Do not edit; edit the overlay instead.\n"
	return append([]byte(header), buf.Bytes()...), nil
}

// Write merges overlay onto the baseline and writes the result to path,
// creating parent directories as needed.
func Write(path string, overlay []byte) error {
	merged, err := Merge(overlay)
	if err != nil {
		return err
	}
	if dir := filepath.Dir(path); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("create config directory %s: %w", dir, err)
		}
	}
	if err := os.WriteFile(path, merged, 0o600); err != nil {
		return fmt.Errorf("write config to %s: %w", path, err)
	}
	return nil
}

func mergeMaps(base, overlay map[string]any) map[string]any {
	out := make(map[string]any, len(base)+len(overlay))
	for k, v := range base {
		out[k] = v
	}
	for k, ov := range overlay {
		bv, exists := out[k]
		if !exists {
			out[k] = ov
			continue
		}
		bm, baseIsMap := bv.(map[string]any)
		om, overlayIsMap := ov.(map[string]any)
		if baseIsMap && overlayIsMap {
			out[k] = mergeMaps(bm, om)
			continue
		}
		out[k] = ov
	}
	return out
}
