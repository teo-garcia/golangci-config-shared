func TestBaselineIsValidYAMLWithSchemaVersion2(t *testing.T) {
	t.Parallel()

	cfg := decode(t, golangciconfig.Baseline())

	if got := cfg["version"]; got != "2" {
		t.Fatalf("version = %v, want \"2\"", got)
	}
}

func TestBaselineReturnsACopy(t *testing.T) {
	t.Parallel()

	first := golangciconfig.Baseline()
	first[0] = 'X'

	if second := golangciconfig.Baseline(); second[0] == 'X' {
		t.Fatal("Baseline() leaked its backing array to the caller")
	}
}

// Formatters must never appear under `linters`; golangci-lint v2 rejects the
// config outright if they do.
func TestFormattersAreNotListedAsLinters(t *testing.T) {
	t.Parallel()

	cfg := decode(t, golangciconfig.Baseline())
	linters, ok := cfg["linters"].(map[string]any)
	if !ok {
		t.Fatal("linters section missing")
	}

	formatterNames := map[string]bool{
		"gci": true, "gofmt": true, "gofumpt": true,
		"goimports": true, "golines": true, "swaggo": true,
	}
	for _, key := range []string{"enable", "disable"} {
		for _, name := range toStrings(linters[key]) {
			if formatterNames[name] {
				t.Errorf("linters.%s contains formatter %q; it belongs in formatters.enable", key, name)
			}
		}
	}
}

func TestBaselineEnablesBothLintersAndFormatters(t *testing.T) {
	t.Parallel()

	cfg := decode(t, golangciconfig.Baseline())

	linters, ok := cfg["linters"].(map[string]any)
	if !ok || len(toStrings(linters["enable"])) == 0 {
		t.Error("linters.enable is empty; the package must own linting")
	}

	formatters, ok := cfg["formatters"].(map[string]any)
	if !ok {
		t.Fatal("formatters section missing; the package must own formatting too")
	}
	enabled := toStrings(formatters["enable"])
	if len(enabled) == 0 {
		t.Fatal("formatters.enable is empty; the package must own formatting too")
	}
	if !contains(enabled, "gofumpt") {
		t.Errorf("formatters.enable = %v, want it to include gofumpt", enabled)
	}
}

func TestMergeWithoutOverlayReturnsBaselineSemantics(t *testing.T) {
	t.Parallel()

	merged, err := golangciconfig.Merge(nil)
	if err != nil {
		t.Fatalf("Merge(nil) returned error: %v", err)
	}

	want := decode(t, golangciconfig.Baseline())
	got := decode(t, merged)

	if len(got) != len(want) {
		t.Fatalf("merged config has %d top-level keys, baseline has %d", len(got), len(want))
	}
	for key := range want {
		if _, ok := got[key]; !ok {
			t.Errorf("merged config dropped top-level key %q", key)
		}
	}
}

func TestMergeDeepMergesNestedMaps(t *testing.T) {
	t.Parallel()

	overlay := []byte("run:\n  timeout: 90s\n")

	cfg := decode(t, mustMerge(t, overlay))
	run, ok := cfg["run"].(map[string]any)
	if !ok {
		t.Fatal("run section missing after merge")
	}

	if got := run["timeout"]; got != "90s" {
		t.Errorf("run.timeout = %v, want 90s", got)
	}
	// Sibling keys under the same map must survive the merge.
	if _, ok := run["tests"]; !ok {
		t.Error("run.tests was dropped; merge replaced the map instead of merging it")
	}
}

func TestMergeReplacesSequencesInsteadOfAppending(t *testing.T) {
	t.Parallel()

	overlay := []byte("linters:\n  enable:\n    - govet\n")

	cfg := decode(t, mustMerge(t, overlay))
	linters, _ := cfg["linters"].(map[string]any)
	enabled := toStrings(linters["enable"])

	if len(enabled) != 1 || enabled[0] != "govet" {
		t.Errorf("linters.enable = %v, want exactly [govet]; sequences must be replaced so consumers can narrow them", enabled)
	}
	// A sibling key in the same map is still merged, not clobbered.
	if _, ok := linters["settings"]; !ok {
		t.Error("linters.settings was dropped by a sequence override")
	}
}

func TestMergeAddsKeysAbsentFromBaseline(t *testing.T) {
	t.Parallel()

	overlay := []byte("severity:\n  default: error\n")

	cfg := decode(t, mustMerge(t, overlay))
	severity, ok := cfg["severity"].(map[string]any)
	if !ok {
		t.Fatal("overlay-only section was not added")
	}
	if got := severity["default"]; got != "error" {
		t.Errorf("severity.default = %v, want error", got)
	}
}

func TestMergeRejectsMalformedOverlay(t *testing.T) {
	t.Parallel()

	if _, err := golangciconfig.Merge([]byte("run:\n\ttimeout: bad\n")); err == nil {
		t.Fatal("Merge accepted malformed YAML; a broken overlay must fail loudly")
	}
}

func TestWriteCreatesParentDirectoriesAndGeneratedHeader(t *testing.T) {
	t.Parallel()

	path := filepath.Join(t.TempDir(), "nested", "dir", ".golangci.yml")
	if err := golangciconfig.Write(path, []byte("run:\n  timeout: 30s\n")); err != nil {
		t.Fatalf("Write returned error: %v", err)
	}

	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("generated config unreadable: %v", err)
	}
	if !strings.HasPrefix(string(data), "# Generated by golangci-config-shared") {
		t.Error("generated config is missing the do-not-edit header")
	}

	cfg := decode(t, data)
	run, _ := cfg["run"].(map[string]any)
	if got := run["timeout"]; got != "30s" {
		t.Errorf("run.timeout = %v, want 30s", got)
	}
}

func decode(t *testing.T, data []byte) map[string]any {
	t.Helper()
	cfg := map[string]any{}
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		t.Fatalf("config is not valid YAML: %v", err)
	}
	return cfg
}

func mustMerge(t *testing.T, overlay []byte) []byte {
	t.Helper()
	merged, err := golangciconfig.Merge(overlay)
	if err != nil {
		t.Fatalf("Merge returned error: %v", err)
	}
	return merged
}

func toStrings(v any) []string {
	items, ok := v.([]any)
	if !ok {
		return nil
	}
	out := make([]string, 0, len(items))
	for _, item := range items {
		if s, ok := item.(string); ok {
			out = append(out, s)
		}
	}
	return out
}

func contains(haystack []string, needle string) bool {
	for _, s := range haystack {
		if s == needle {
			return true
		}
	}
	return false
}
